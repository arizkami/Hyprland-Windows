#!/usr/bin/env python3
"""Generates windows/compat/include/wayland-server-protocol.h from wayland.xml.

The Windows build links no Wayland server, but shared Hyprland code uses the core
protocol's enums (output transforms, pointer/keyboard states, ...). This emits the
same enum and interface declarations wayland-scanner would, without request/event
glue. Usage: generate-wayland-protocol.py <wayland.xml> <output header>
"""
import sys
import xml.etree.ElementTree as ET


def entry_value(entry):
    return entry.get('value')


def main(source, target):
    protocol = ET.parse(source).getroot()
    lines = [
        '/* Generated by windows/compat/generate-wayland-protocol.py from wayland.xml. Do not edit. */',
        '/* Enums and interface declarations only; the Windows build has no Wayland server. */',
        '#ifndef WAYLAND_SERVER_PROTOCOL_H',
        '#define WAYLAND_SERVER_PROTOCOL_H',
        '',
        '#include <stdint.h>',
        '#include <stddef.h>',
        '#include "wayland-server-core.h"',
        '',
        '#ifdef  __cplusplus',
        'extern "C" {',
        '#endif',
        '',
    ]

    for interface in protocol.findall('interface'):
        name = interface.get('name')
        lines.append(f'extern const struct wl_interface {name}_interface;')
    lines.append('')

    for interface in protocol.findall('interface'):
        name = interface.get('name')
        for enum in interface.findall('enum'):
            enum_name = f'{name}_{enum.get("name")}'
            guard = f'{enum_name.upper()}_ENUM'
            lines += [f'#ifndef {guard}', f'#define {guard}', f'enum {enum_name} {{']
            for entry in enum.findall('entry'):
                lines.append(f'\t{enum_name.upper()}_{entry.get("name").upper()} = {entry_value(entry)},')
            lines += ['};', f'#endif /* {guard} */', '']

    lines += [
        '#ifdef  __cplusplus',
        '}',
        '#endif',
        '',
        '#endif',
        '',
    ]
    with open(target, 'w', encoding='utf-8', newline='\n') as output:
        output.write('\n'.join(lines))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
